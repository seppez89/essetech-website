def panel(page):
    data = FACTS[page]
    cells = []
    for label, value, note in data["facts"]:
        cells.append(
            '                    <div><dt class="text-xs font-bold uppercase tracking-wider text-fire-600">%s</dt>'
            '<dd class="mt-1 font-bold text-navy-900">%s</dd>'
            '<dd class="mt-1 text-sm leading-relaxed text-gray-600">%s</dd></div>' % (label, value, note)
        )
    columns = "sm:grid-cols-2 lg:grid-cols-4"
    return (
        START
        + '    <section class="py-10 md:py-14 bg-white" aria-labelledby="key-facts">\n'
        + '        <div class="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8">\n'
        + '            <div class="rounded-3xl border border-navy-100 bg-navy-50 p-6 sm:p-8 lg:p-10">\n'
        + '                <h2 id="key-facts" class="text-2xl sm:text-3xl font-black text-navy-900">%s</h2>\n' % data["title"]
        + '                <p class="mt-3 max-w-3xl text-gray-600 leading-relaxed">%s</p>\n' % data["intro"]
        + '                <dl class="mt-8 grid %s gap-x-8 gap-y-8">\n' % columns
        + "\n".join(cells) + "\n"
        + "                </dl>\n"
        + '                <p class="mt-8 text-sm text-gray-600">Prices are in Australian dollars and exclude GST. Checked <time datetime="%s">%s</time>. '
          '<a href="/pricing-adelaide.html" class="font-semibold text-fire-600 underline hover:text-fire-700">See the full price list</a>.</p>\n' % (CHECKED_ISO, CHECKED_TEXT)
        + "            </div>\n"
        + "        </div>\n"
        + "    </section>\n"
        + END
    )


def main():
    for page in FACTS:
        html = open(page, encoding="utf-8").read()
        block = panel(page)
        if START in html:
            html = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, html, flags=re.S)
            action = "refreshed"
        elif "before" in FACTS[page]:
            at = html.index(FACTS[page]["before"])
            html = html[:at] + block.lstrip(" ") + "\n    " + html[at:]
            action = "added"
        else:
            main_at = html.index("<main")
            hero_end = html.index("</section>", main_at) + len("</section>")
            newline = html.index("\n", hero_end) + 1
            html = html[:newline] + "\n" + block + html[newline:]
            action = "added"
        open(page, "w", encoding="utf-8").write(html)
        print("%-9s %s" % (action, page))


if __name__ == "__main__":
    sys.exit(main())
